    /**
     * Sidebar items the given staff member may see, grouped by heading.
     *
     * @return array<string, list<self>>
     */
    public static function visibleTo(?SystemUser $staff): array
    {
        $groups = [];
        foreach (self::cases() as $module) {
            if ($staff?->can($module->permission())) {
                $groups[$module->group()][] = $module;
            }
        }

        return $groups;
    }
