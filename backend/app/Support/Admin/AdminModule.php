    public function label(): string
    {
        return match ($this) {
            self::Dashboard => 'Dashboard',
            self::Users => 'Users',
            self::Services => 'Services',
            self::Transactions => 'Transactions',
            self::Purchases => 'Purchases',
            self::Providers => 'Providers',
            self::Payments => 'Payments',
            self::Wallet => 'Wallet',
            self::Withdrawals => 'Withdrawals',
            self::Referrals => 'Referral & Commission',
            self::Notifications => 'Notifications',
            self::Support => 'Support',
            self::Reports => 'Reports',
            self::Settings => 'Settings',
            self::SystemUsers => 'System Users',
            self::Roles => 'Roles & Permissions',
        };
    }

    /** Permission needed to see the menu item and open the page. */
    public function permission(): string
    {
        return (match ($this) {
            self::Dashboard => SystemPermission::AdminAccess,
            self::Users => SystemPermission::CustomersView,
            self::SystemUsers => SystemPermission::SystemUsersManage,
            self::Roles => SystemPermission::RolesView,
            self::Settings => SystemPermission::SettingsView,
            self::Services => SystemPermission::ServicesView,
            self::Transactions => SystemPermission::TransactionsView,
            self::Purchases => SystemPermission::PurchasesView,
            self::Providers => SystemPermission::ProvidersView,
            self::Payments => SystemPermission::PaymentsView,
            self::Wallet => SystemPermission::WalletView,
            self::Withdrawals => SystemPermission::WithdrawalsView,
            self::Referrals => SystemPermission::ReferralsView,
            self::Notifications => SystemPermission::NotificationsView,
            self::Support => SystemPermission::SupportView,
            self::Reports => SystemPermission::ReportsView,
        })->value;
    }

    /** Roadmap phase in which the module is built (see ROADMAP.md); null once it is built. */
    public function plannedPhase(): ?int
    {
        return match ($this) {
            self::Dashboard, self::Settings, self::SystemUsers, self::Roles, self::Users, self::Services, self::Providers,
            self::Transactions, self::Wallet, self::Payments, self::Purchases, self::Referrals => null,
            self::Withdrawals => 14,
            self::Notifications, self::Support => 15,
            self::Reports => 16,
        };
    }

    public function isBuilt(): bool
    {
        return $this->plannedPhase() === null;
    }

    public function routeName(): string
    {
        return $this === self::Dashboard ? 'admin.dashboard' : 'admin.'.$this->value;
    }

    /** URL path below /admin. */
    public function path(): string
    {
        return $this === self::Dashboard ? '/' : $this->value;
    }

    /** Sidebar group heading. */
    public function group(): string
    {
        return match ($this) {
            self::Dashboard => 'Overview',
            self::Users, self::Services, self::Transactions, self::Purchases, self::Providers => 'Operations',
            self::Payments, self::Wallet, self::Withdrawals, self::Referrals => 'Finance',
            self::Notifications, self::Support, self::Reports => 'Engagement',
            self::Settings, self::SystemUsers, self::Roles => 'Administration',
        };
    }

